CREATE TABLE IF NOT EXISTS store_connections (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  store_id INT UNSIGNED NOT NULL,
  connection_type VARCHAR(50) NOT NULL DEFAULT 'woocommerce_plugin',
  mode VARCHAR(50) NOT NULL DEFAULT 'plugin_api',
  status VARCHAR(50) NOT NULL DEFAULT 'draft',
  wp_base_url VARCHAR(255) NULL,
  plugin_token VARCHAR(190) NULL,
  plugin_status VARCHAR(50) NOT NULL DEFAULT 'not_tested',
  remote_site_name VARCHAR(190) NULL,
  remote_home_url VARCHAR(255) NULL,
  remote_wp_version VARCHAR(50) NULL,
  remote_wc_version VARCHAR(50) NULL,
  remote_product_count INT NOT NULL DEFAULT 0,
  remote_category_count INT NOT NULL DEFAULT 0,
  last_discovery_at DATETIME NULL,
  last_import_at DATETIME NULL,
  last_error TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_store_connection_store (store_id),
  KEY idx_store_connection_status (status),
  KEY idx_store_connection_type (connection_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
